/**
 * contract-materializer.mjs — deterministic pre-prompt artifact materializer.
 *
 * Runs inside the pi Container before any chat turn. It handles simple,
 * smoke-grade contracts by issuing a pi RPC bash command that writes an
 * artifact file into the stage workdir. This keeps production smoke harnesses
 * focused on dispatch, R2 egress, gate evaluation, and observability instead
 * of relying on the model to choose filesystem tools.
 */

export function shellQuote(s) {
  return "'" + String(s).replace(/'/g, "'\\''") + "'"
}

export function jsonPlaceholderValue(field, input) {
  if (field === 'runId') return input.runId ?? input.context?.runId ?? 'unknown'
  if (/^(elapsedMs|durationMs|.*Count|.*Bytes|.*Size|.*Total)$/i.test(field)) return 0
  if (/^(ok|passed|success|valid)$/i.test(field)) return true
  if (/^(status|state|result|verdict)$/i.test(field)) return 'ok'
  return ''
}

export function patternSample(pattern) {
  return String(pattern)
    .replace(/^\^/, '')
    .replace(/\$$/, '')
    .replace(/\\b/g, '')
    .replace(/\\s[+*?]?/g, ' ')
    .replace(/\.\*/g, 'value')
    .replace(/\.\+/g, 'value')
    .replace(/\\+([\\.+*?^${}()|[\]/-])/g, '$1')
    .trim()
}

export function materializedContractContent(contract, input) {
  const body = contract.body
  if (body?.kind === 'exact_line') {
    return `${body.line}\n`
  }
  if (body?.kind === 'json' && Array.isArray(body.requiredFields) && body.requiredFields.length > 0) {
    const payload = {}
    for (const field of body.requiredFields) {
      if (typeof field === 'string' && field.length > 0) {
        payload[field] = jsonPlaceholderValue(field, input)
      }
    }
    return `${JSON.stringify(payload, null, 2)}\n`
  }
  if (body?.kind === 'text') {
    const lines = []
    for (const pattern of body.requiredPatterns ?? []) {
      const sample = patternSample(pattern)
      if (sample) lines.push(sample)
    }
    if (lines.length === 0) lines.push(`${contract.artifact} generated by Factory contract materializer.`)
    return `${dedupe(lines).join('\n')}\n`
  }
  if (body?.kind === 'markdown') {
    const lines = [`# ${contract.artifact}`]
    for (const section of body.requiredSections ?? []) {
      lines.push('', `## ${section}`)
      lines.push(`${section} content generated by Factory contract materializer.`)
    }
    for (const pattern of body.requiredPatterns ?? []) {
      const sample = patternSample(pattern)
      if (sample) lines.push(sample)
    }
    return `${dedupe(lines).join('\n')}\n`
  }
  return undefined
}

export function contractMaterializeCommand(contract, input) {
  if (!/^[A-Za-z0-9._-]+$/.test(contract.artifact)) return undefined
  const content = materializedContractContent(contract, input)
  if (content === undefined) return undefined
  return {
    artifact: contract.artifact,
    kind: contract.body.kind,
    command: `printf '%s' ${shellQuote(content)} > ${shellQuote(contract.artifact)}`,
  }
}

function dedupe(lines) {
  const out = []
  const seen = new Set()
  for (const line of lines) {
    if (seen.has(line)) continue
    seen.add(line)
    out.push(line)
  }
  return out
}
